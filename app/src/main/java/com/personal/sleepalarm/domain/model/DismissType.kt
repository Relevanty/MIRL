package com.personal.sleepalarm.domain.model

/**
 * Способ завершения сессии будильника.
 */
enum class DismissType {
    /**
     * Пользователь решил задачу и выключил будильник.
     */
    NORMAL,

    /**
     * Пользователь отложил будильник на один цикл.
     */
    SNOOZE,

    /**
     * Будильник не был выключен пользователем,
     * например телефон был выключен или сессия устарела.
     */
    MISSED,

    /**
     * Сессия была отменена вручную до пробуждения.
     */
    CANCELLED
}