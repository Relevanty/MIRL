package com.personal.sleepalarm.domain.model

/**
 * Состояние отдельной lucid-подсказки.
 */
enum class CueEventState {
    /**
     * Подсказка запланирована, но ещё не проиграна.
     */
    SCHEDULED,

    /** Подсказка атомарно захвачена одним проигрывателем. */
    PLAYING,

    /**
     * Подсказка успешно проиграна.
     */
    PLAYED,

    /**
     * Подсказка пропущена, например потому что попала в финальный цикл.
     */
    SKIPPED,

    /**
     * Подсказка отменена вместе с сессией.
     */
    CANCELLED
}
